defmodule Ksc.Compiler.ElixirCompiler do
  @moduledoc "Generates Elixir source code from ClassSpec structs."

  alias Ksc.Format.{ClassSpec, AttrSpec, InstanceSpec}
  alias Ksc.Compiler.Utils

  @doc """
  Compile a ClassSpec into an Elixir source code string.

  Options:
    - `:writer` — when `true`, also generate `to_binary/1` + `to_file/2` and the
      writer support functions on every non-parameterised module. Default `false`.
  """
  def compile(spec, opts \\ [])

  def compile(%ClassSpec{} = spec, opts) do
    mod_name = Utils.to_module_name(spec.id)
    type_registry = build_type_registry(spec, mod_name)
    # Collect ALL enums from the entire type hierarchy
    all_enums = collect_all_enums(spec)
    writer? = Keyword.get(opts, :writer, false)
    compile_module(spec, nil, type_registry, mod_name, all_enums, writer?)
  end

  # Recursively collect all enums from the entire type hierarchy
  defp collect_all_enums(%ClassSpec{} = spec) do
    own_enums = spec.enums

    child_enums =
      Enum.reduce(spec.types, %{}, fn {_name, type_spec}, acc ->
        Map.merge(acc, collect_all_enums(type_spec))
      end)

    Map.merge(own_enums, child_enums)
  end

  defp build_type_registry(%ClassSpec{} = spec, prefix) do
    Enum.reduce(spec.types, %{}, fn {name, type_spec}, acc ->
      mod_path = "#{prefix}.#{Utils.to_module_name(name)}"
      acc = Map.put(acc, name, mod_path)
      nested = build_type_registry(type_spec, mod_path)
      Map.merge(acc, nested)
    end)
  end

  defp compile_module(
         %ClassSpec{} = spec,
         parent_endian,
         type_registry,
         mod_name,
         all_enums,
         writer?
       ) do
    endian = spec.endian || parent_endian
    # For switch-on endian, pass down :dynamic so child types know
    effective_endian =
      case endian do
        {:switch, _, _} -> :dynamic
        other -> other
      end

    # Merge this module's enums with inherited ones
    all_enums = Map.merge(all_enums, spec.enums)

    {enum_defs, enum_reverse_attr} = compile_enums(all_enums)

    nested_modules =
      Enum.map(spec.types, fn {name, type_spec} ->
        nested_mod_name = "#{mod_name}.#{Utils.to_module_name(name)}"
        # Pass effective_endian for non-switch types, full endian for the type with the switch
        child_endian =
          case type_spec.endian do
            nil -> effective_endian
            _ -> type_spec.endian
          end

        # Inherit bit_endian from parent if not set
        child_spec = %{type_spec | endian: child_endian}

        child_spec =
          if child_spec.bit_endian == nil and spec.bit_endian != nil do
            %{child_spec | bit_endian: spec.bit_endian}
          else
            child_spec
          end

        # Inherit encoding from parent if not set
        child_spec =
          if child_spec.encoding == nil and spec.encoding != nil do
            %{child_spec | encoding: spec.encoding}
          else
            child_spec
          end

        # Propagate ks_debug to child types
        child_spec = if spec.ks_debug, do: %{child_spec | ks_debug: true}, else: child_spec

        compile_module(
          child_spec,
          effective_endian,
          type_registry,
          nested_mod_name,
          all_enums,
          writer?
        )
      end)

    eager_instances = compute_eager_instances(spec, endian, type_registry)
    parse_fn = compile_parse_function(spec, endian, type_registry, eager_instances)
    instance_fns = compile_instances(spec.instances, endian, type_registry, spec, eager_instances)
    public_api = compile_public_api(spec, writer?)
    sizeof_fn = compile_sizeof(spec, endian)

    writer_fn =
      if writer?, do: compile_writer_function(spec, endian, type_registry), else: ""

    body_parts =
      [enum_defs | nested_modules] ++
        [public_api, parse_fn | instance_fns] ++ [sizeof_fn, writer_fn]

    body =
      body_parts
      |> Enum.reject(&is_nil/1)
      |> Enum.reject(&(&1 == ""))
      |> Enum.join("\n\n")

    # Only include @kaitai_enum_reverse if the body actually references it
    body =
      if String.contains?(body, "@kaitai_enum_reverse") do
        reverse_line =
          if enum_reverse_attr != "", do: enum_reverse_attr, else: "@kaitai_enum_reverse %{}"

        reverse_line <> "\n" <> body
      else
        body
      end

    short_name = mod_name |> String.split(".") |> List.last()

    """
    defmodule #{short_name} do
      @moduledoc \"\"\"
      Auto-generated by [ksc](https://github.com/pjullrich/ksc) from a Kaitai Struct `.ksy` definition.
      Do not edit manually — any changes will be overwritten on recompilation.
      \"\"\"

    #{Utils.indent(body, 1)}
    end
    """
    |> String.trim()
  end

  # Auto-number anonymous fields: nil/empty id -> "_anon_0", "_anon_1", etc.
  defp number_anonymous_fields(seq) do
    {result, _} =
      Enum.reduce(seq, {[], 0}, fn attr, {acc, anon_idx} ->
        if attr.id == nil or attr.id == "" do
          {acc ++ [%{attr | id: "_anon_#{anon_idx}"}], anon_idx + 1}
        else
          {acc ++ [attr], anon_idx}
        end
      end)

    result
  end

  defp compile_public_api(%ClassSpec{} = spec, writer?) do
    has_instances = map_size(spec.instances) > 0
    has_params = (spec.params || []) != []

    # Don't generate from_binary for parameterized types
    if has_params do
      ""
    else
      # Check for seq fields that have deferred instance resolution
      deferred_resolve_fields =
        Enum.filter(spec.seq, fn attr ->
          is_binary(attr.type) and attr.type != "" and
            (fn ->
               {base_type, _} = parse_type_args(attr.type)
               has_root_io_instances?(base_type, spec)
             end).()
        end)

      deferred_code =
        if deferred_resolve_fields != [] do
          lines =
            Enum.map(deferred_resolve_fields, fn attr ->
              {base_type, _} = parse_type_args(attr.type)
              type_mod = Utils.to_module_name(base_type)

              if attr.repeat != nil do
                """
                result = Map.put(result, :#{attr.id}, Enum.map(result[:#{attr.id}], fn item ->
                  item = Map.put(item, :_root, result)
                  #{type_mod}.resolve_instances(item, data)
                end))
                """
                |> String.trim()
              else
                """
                result = Map.put(result, :#{attr.id}, #{type_mod}.resolve_instances(Map.put(result[:#{attr.id}], :_root, result), data))
                """
                |> String.trim()
              end
            end)

          Enum.join(lines, "\n")
        else
          nil
        end

      from_binary =
        if has_instances or deferred_code != nil do
          deferred_str = if deferred_code, do: "\n" <> deferred_code, else: ""

          resolve_str =
            if has_instances, do: "\nresolve_instances(result, data)", else: "\nresult"

          """
          def from_file(path) do
            from_binary(File.read!(path))
          end

          def from_binary(data) when is_binary(data) do
            {result, _rest} = parse(data, nil)
            result = Map.put(result, :_root, result)
            result = Map.put(result, :_io_data, data)#{deferred_str}#{resolve_str}
          end
          """
        else
          """
          def from_file(path) do
            from_binary(File.read!(path))
          end

          def from_binary(data) when is_binary(data) do
            {result, _rest} = parse(data, nil)
            result
          end
          """
        end

      writer_api =
        if writer? do
          """


          def to_file(path, map) do
            File.write!(path, to_binary(map))
          end

          def to_binary(map) do
            to_binary(map, nil, nil)
          end
          """
        else
          ""
        end

      String.trim(from_binary) <> writer_api
    end

    # has_params else
  end

  defp compute_eager_instances(%ClassSpec{} = spec, _endian, _type_registry) do
    if spec.seq == [] do
      []
    else
      seq_with_ids = number_anonymous_fields(spec.seq)
      instance_names = Map.keys(spec.instances)

      Enum.filter(instance_names, fn inst_name ->
        inst = spec.instances[inst_name]

        is_referenced =
          Enum.any?(seq_with_ids, fn attr ->
            type_str = if is_binary(attr.type), do: attr.type, else: ""

            expr_text =
              Enum.join(
                [
                  attr.size || "",
                  attr.if_expr || "",
                  attr.repeat_expr || "",
                  attr.repeat_until || "",
                  type_str
                ],
                " "
              )

            String.contains?(expr_text, inst_name)
          end)

        is_referenced and (inst.value != nil or inst.pos != nil)
      end)
    end
  end

  defp compile_parse_function(%ClassSpec{} = spec, endian, type_registry, eager_instances) do
    params = spec.params || []
    param_names = Enum.map(params, fn p -> "var_#{p.id}" end)
    has_params = params != []

    # For downstream code, convert switch-on endian to :dynamic
    parse_endian =
      case endian do
        {:switch, _, _} -> :dynamic
        other -> other
      end

    if spec.seq == [] do
      if has_params do
        args = Enum.join(["data", "root_", "parent_"] ++ param_names, ", ")
        param_map = Enum.map(params, fn p -> "#{p.id}: var_#{p.id}" end) |> Enum.join(", ")

        "def parse(#{args}) do\n  root_ = if(root_ == :none, do: nil, else: root_)\n  {%{#{param_map}, _parent: parent_, _root: root_}, data}\nend"
      else
        "def parse(data, root_, parent_ \\\\ nil) do\n  root_ = if(root_ == :none, do: nil, else: root_)\n  {%{_parent: parent_, _root: root_}, data}\nend"
      end
    else
      seq_with_ids = number_anonymous_fields(spec.seq)

      bit_endian = spec.bit_endian

      field_parses =
        compile_attr_parses_with_bits(seq_with_ids, parse_endian, type_registry, spec, bit_endian)

      # Interleave eager instance computations: insert each before the first field that needs it
      field_parses =
        interleave_eager_instances(
          field_parses,
          seq_with_ids,
          eager_instances,
          spec,
          parse_endian,
          type_registry
        )

      field_names = Enum.map(seq_with_ids, fn attr -> attr.id end)

      # When ks_debug is true, insert Process.put calls after each field for partial parse tracking
      field_parses =
        if spec.ks_debug do
          Enum.zip(field_parses, field_names)
          |> Enum.map(fn {code, name} ->
            code <>
              "\nProcess.put(:_kaitai_debug_partial, Map.put(Process.get(:_kaitai_debug_partial) || %{}, :#{name}, var_#{name}))" <>
              "\nProcess.put(:_kaitai_debug_rest, rest)"
          end)
        else
          field_parses
        end

      # Include params and eager instances in result map
      param_entries = Enum.map(params, fn p -> "#{p.id}: var_#{p.id}" end)
      field_entries = Enum.map(field_names, fn name -> "#{name}: var_#{name}" end)
      eager_entries = Enum.map(eager_instances, fn name -> "#{name}: var_#{name}" end)

      # Check if non-eager instances reference _io.pos (need to track parse position)
      non_eager_inst_exprs =
        Enum.flat_map(spec.instances, fn {name, inst} ->
          if name in eager_instances,
            do: [],
            else: [inst.pos || "", inst.value || "", inst.size || "", inst.if_expr || ""]
        end)
        |> Enum.join(" ")

      non_eager_needs_io_pos = String.contains?(non_eager_inst_exprs, "_io.pos")

      # Store _is_le in result when endian is dynamic (switch expression)
      has_is_le = match?({:switch, _, _}, endian) or endian == :dynamic

      # Generate _sizeof entries for field types (always include if type has known size)
      sizeof_entries =
        (
          type_size = compute_type_size(seq_with_ids, parse_endian, spec)
          self_sizeof = if type_size != nil, do: ["_sizeof: #{type_size}"], else: []

          field_sizeofs =
            Enum.flat_map(seq_with_ids, fn attr ->
              s = attr_fixed_size(attr, parse_endian, spec)
              if s != nil, do: ["_sizeof_#{attr.id}: #{s}"], else: []
            end)

          self_sizeof ++ field_sizeofs
        )

      extra_entries =
        ["_parent: parent_", "_root: if(root_ == :none, do: nil, else: root_)"] ++
          if(has_is_le, do: ["_is_le: var__is_le"], else: []) ++
          if non_eager_needs_io_pos, do: ["_io_pos: byte_size(data) - byte_size(rest)"], else: []

      result_map =
        Enum.join(
          param_entries ++ field_entries ++ eager_entries ++ sizeof_entries ++ extra_entries,
          ", "
        )

      # Check if any user types exist (need result_so_far for parent passing)
      needs_parent_passing =
        Enum.any?(seq_with_ids, fn attr ->
          is_user_type_attr?(attr, parse_endian, type_registry, spec)
        end)

      body = Enum.join(field_parses, "\n")

      # Check if any field or eager instance uses _io.pos or _io.size
      all_exprs = collect_all_expressions(seq_with_ids)

      eager_inst_exprs =
        Enum.flat_map(eager_instances, fn inst_name ->
          inst = spec.instances[inst_name]
          [inst.pos || "", inst.value || "", inst.size || ""]
        end)

      needs_io =
        Enum.any?(all_exprs ++ eager_inst_exprs, fn e ->
          is_binary(e) and
            (String.contains?(e, "_io.pos") or String.contains?(e, "_io.size") or
               String.contains?(e, "_io.eof"))
        end)

      io_init =
        if needs_io do
          # For inline types (no size/terminator), _io refers to the parent's stream.
          # The parent passes its io_size via _io_size in the parent ref so the child
          # computes _io.pos / _io.size relative to the parent stream.
          "io_size = if is_map(parent_) and is_integer(parent_[:_io_size]), do: parent_[:_io_size], else: byte_size(data)"
        else
          nil
        end

      parent_init =
        if needs_parent_passing,
          do:
            "result_so_far = %{_parent: parent_}\nio_data_ = if is_map(parent_), do: parent_[:_io_data] || data, else: data",
          else: nil

      # When root_ is nil (top-level call from from_binary), track root_ as result_so_far
      # so that _root references in child types see the fields parsed so far.
      # For parameterized types, root_ is always passed from the caller, so root_is_self_ is false.
      root_init =
        if needs_parent_passing do
          if has_params do
            "root_is_self_ = false"
          else
            "root_is_self_ = root_ == nil\nroot_ = if root_ == :none, do: nil, else: root_\nresult_so_far = Map.put(result_so_far, :_io_data, io_data_)\nroot_ = if(root_is_self_, do: result_so_far, else: root_)"
          end
        else
          nil
        end

      # Generate _is_le computation for switch-on endian
      is_le_init =
        case endian do
          {:switch, switch_on, cases} ->
            code = compile_is_le_switch(switch_on, cases)
            # Store _is_le in result_so_far for child types
            if needs_parent_passing do
              code <>
                "\nresult_so_far = Map.put(result_so_far, :_is_le, var__is_le)" <>
                "\nroot_ = if(root_is_self_, do: result_so_far, else: root_)"
            else
              code
            end

          :dynamic ->
            # Inherited from parent
            code = "var__is_le = parent_[:_is_le]"

            if needs_parent_passing do
              code <> "\nresult_so_far = Map.put(result_so_far, :_is_le, var__is_le)"
            else
              code
            end

          _ ->
            nil
        end

      debug_init =
        if spec.ks_debug do
          "Process.put(:_kaitai_debug_partial, %{_parent: parent_, _root: if(root_ == :none, do: nil, else: root_)})\nProcess.put(:_kaitai_debug_rest, data)"
        else
          nil
        end

      body_lines =
        [parent_init, root_init, is_le_init, debug_init, body]
        |> Enum.reject(&is_nil/1)
        |> Enum.join("\n")

      # Insert io_pos updates before each field that references _io
      body_lines =
        if needs_io do
          insert_io_pos_updates(body_lines)
        else
          body_lines
        end

      # Only prepend io_size initialization if the body actually uses it
      body_lines =
        if io_init != nil and String.contains?(body_lines, "io_size") do
          io_init <> "\n" <> body_lines
        else
          body_lines
        end

      parse_args =
        if has_params do
          Enum.join(["data", "root_", "parent_"] ++ param_names, ", ")
        else
          "data, root_, parent_ \\\\ nil"
        end

      debug_cleanup =
        if spec.ks_debug do
          "\nProcess.put(:_kaitai_debug_partial, nil)\nProcess.put(:_kaitai_debug_rest, nil)"
        else
          ""
        end

      """
      def parse(#{parse_args}) do
        rest = data
      #{Utils.indent(body_lines, 1)}#{debug_cleanup}
        {%{#{result_map}}, rest}
      end
      """
      |> String.trim()
    end
  end

  # Group attrs into runs of consecutive bit fields vs non-bit fields, producing code
  defp compile_attr_parses_with_bits(attrs, endian, type_registry, spec, bit_endian) do
    # Group into runs: {:bit, [attrs]} or {:normal, attr}
    groups = group_bit_runs(attrs, endian, type_registry, spec)

    needs_parent =
      Enum.any?(attrs, fn attr ->
        is_user_type_attr?(attr, endian, type_registry, spec)
      end)

    Enum.map(groups, fn
      {:normal, attr} ->
        code = compile_attr_parse(attr, endian, type_registry, spec)

        if needs_parent do
          code <>
            "\nresult_so_far = Map.put(result_so_far, :#{attr.id}, var_#{attr.id})" <>
            "\nroot_ = if(root_is_self_, do: result_so_far, else: root_)"
        else
          code
        end

      {:bit_run, bit_attrs} ->
        # Generate code that uses bit accumulator state
        # Track endian changes to insert alignment when switching
        default_bit_endian_val = if bit_endian == "le", do: :le, else: :be

        # Get effective endian for each attr
        attr_endians =
          Enum.map(bit_attrs, fn attr ->
            {_match, bit_info} = type_to_pattern(attr.type, endian, attr, type_registry, spec)

            case bit_info do
              {:bit, _s, e} when e != nil -> e
              _ -> default_bit_endian_val
            end
          end)

        init_code = "bits_state = {0, 0, rest}"

        {field_codes, _prev_endian} =
          Enum.zip(bit_attrs, attr_endians)
          |> Enum.map_reduce(nil, fn {attr, field_endian}, prev_endian ->
            var = "var_#{attr.id}"
            {_match, bit_info} = type_to_pattern(attr.type, endian, attr, type_registry, spec)
            {:bit, bit_size, _} = bit_info

            bit_fn = if field_endian == :le, do: "read_bits_le", else: "read_bits_be"

            # When switching endian within a run, realign first
            realign =
              if prev_endian != nil and prev_endian != field_endian do
                "rest = Ksc.Stream.align_to_byte(bits_state)\nbits_state = {0, 0, rest}\n"
              else
                ""
              end

            read_code =
              realign <> "{#{var}, bits_state} = Ksc.Stream.#{bit_fn}(bits_state, #{bit_size})"

            # b1 yields boolean (unless enum is applied)
            read_code =
              if bit_size == 1 and attr.enum == nil do
                read_code <> "\n#{var} = #{var} != 0"
              else
                read_code
              end

            # Wrap in conditional if needed
            code =
              if attr.if_expr != nil do
                condition = translate_expr(attr.if_expr)

                """
                {#{var}, bits_state} = if #{condition} do
                  #{read_code}
                  {#{var}, bits_state}
                else
                  {nil, bits_state}
                end
                """
                |> String.trim()
              else
                maybe_wrap_enum(read_code, attr, var)
              end

            {code, field_endian}
          end)

        align_code = "rest = Ksc.Stream.align_to_byte(bits_state)"

        parent_updates =
          if needs_parent do
            Enum.flat_map(bit_attrs, fn attr ->
              [
                "result_so_far = Map.put(result_so_far, :#{attr.id}, var_#{attr.id})",
                "root_ = if(root_is_self_, do: result_so_far, else: root_)"
              ]
            end)
          else
            []
          end

        Enum.join([init_code | field_codes] ++ [align_code] ++ parent_updates, "\n")
    end)
  end

  defp group_bit_runs(attrs, endian, type_registry, spec) do
    {groups, current_bits} =
      Enum.reduce(attrs, {[], []}, fn attr, {groups, current_bits} ->
        if is_bit_type?(attr, endian, type_registry, spec) do
          {groups, current_bits ++ [attr]}
        else
          if current_bits != [] do
            {groups ++ [{:bit_run, current_bits}, {:normal, attr}], []}
          else
            {groups ++ [{:normal, attr}], []}
          end
        end
      end)

    if current_bits != [] do
      groups ++ [{:bit_run, current_bits}]
    else
      groups
    end
  end

  defp is_user_type_attr?(%AttrSpec{} = attr, endian, type_registry, spec) do
    case type_to_pattern(attr.type, endian, attr, type_registry, spec) do
      {_, :user_type} -> true
      # switch may contain user types
      {_, :switch} -> true
      _ -> false
    end
  end

  defp is_bit_type?(%AttrSpec{} = attr, endian, type_registry, spec) do
    # Don't treat repeated bit fields as bit-run candidates - they need repeat loop handling
    if attr.repeat != nil do
      false
    else
      case type_to_pattern(attr.type, endian, attr, type_registry, spec) do
        {_, {:bit, _, _}} -> true
        _ -> false
      end
    end
  end

  defp compile_attr_parse(%AttrSpec{} = attr, endian, type_registry, spec) do
    var = "var_#{attr.id}"

    cond do
      attr.contents != nil ->
        compile_contents_parse(attr, var)

      attr.repeat != nil ->
        compile_repeat_parse(attr, endian, var, type_registry, spec)

      attr.if_expr != nil ->
        compile_conditional_parse(attr, endian, var, type_registry, spec)

      true ->
        compile_simple_parse(attr, endian, var, type_registry, spec)
    end
  end

  defp compile_simple_parse(%AttrSpec{} = attr, endian, var, type_registry, spec) do
    # Check for dynamic endian on endian-dependent types
    effective_endian =
      case endian do
        {:switch, _, _} -> :dynamic
        other -> other
      end

    is_dynamic = effective_endian == :dynamic
    is_endian_dep = is_dynamic and is_endian_dependent_type?(attr.type)

    if is_endian_dep do
      compile_dynamic_endian_parse(attr, var, type_registry, spec)
    else
      compile_static_endian_parse(attr, effective_endian, var, type_registry, spec)
    end
  end

  defp is_endian_dependent_type?(type) when is_binary(type) do
    type in ~w(u2 s2 u4 s4 u8 s8 f4 f8)
  end

  defp is_endian_dependent_type?(_), do: false

  defp compile_dynamic_endian_parse(%AttrSpec{} = attr, var, type_registry, spec) do
    le_attr = %{attr | if_expr: nil, repeat: nil}
    be_attr = le_attr
    {le_match, _} = type_to_pattern(attr.type, :le, le_attr, type_registry, spec)
    {be_match, _} = type_to_pattern(attr.type, :be, be_attr, type_registry, spec)

    code =
      """
      {#{var}, rest} = if var__is_le do
        <<val::#{le_match}, r::binary>> = rest
        {val, r}
      else
        <<val::#{be_match}, r::binary>> = rest
        {val, r}
      end
      """
      |> String.trim()

    maybe_wrap_enum(code, attr, var)
  end

  defp compile_static_endian_parse(%AttrSpec{} = attr, endian, var, type_registry, spec) do
    {match, type_info} = type_to_pattern(attr.type, endian, attr, type_registry, spec)

    code =
      case type_info do
        :user_type ->
          {base_type, type_args} = parse_type_args(attr.type)
          type_mod = resolve_type_module(base_type, type_registry, spec)
          # Check if this is a cross-module (imported) type - pass nil for parent/root
          is_imported_type = is_cross_module_type?(base_type, spec)
          # Build result map reference for parent passing
          parent_ref =
            if is_imported_type do
              "nil"
            else
              case attr.parent do
                "_parent" -> "parent_"
                "_root" -> "root_"
                false -> "nil"
                nil -> "result_so_far"
                other when is_binary(other) -> translate_expr(other)
                _ -> "result_so_far"
              end
            end

          root_ref = if is_imported_type, do: ":none", else: "root_"
          # Translate type arguments
          args_str =
            if type_args != [] do
              ", " <> Enum.map_join(type_args, ", ", &translate_expr/1)
            else
              ""
            end

          cond do
            attr.size != nil ->
              # Sized user type: extract substream, apply processing, then parse
              size_expr = translate_expr(attr.size)

              extract =
                """
                size_#{attr.id} = #{size_expr}
                <<#{var}_data::binary-size(size_#{attr.id}), rest::binary>> = rest
                """
                |> String.trim()

              # Apply pad/term/process to extracted data before parsing
              processing = build_data_processing(attr, "#{var}_data")

              parse_line =
                "{#{var}, _} = #{type_mod}.parse(#{var}_data, #{root_ref}, #{parent_ref}#{args_str})"

              resolve_line = "#{var} = #{type_mod}.resolve_instances(#{var}, #{var}_data)"
              sizeof_line = "#{var} = Map.put(#{var}, :_sizeof, size_#{attr.id})"
              io_size_line = "#{var} = Map.put(#{var}, :_io_size, size_#{attr.id})"
              io_data_line = "#{var} = Map.put(#{var}, :_io_data, #{var}_data)"

              Enum.join(
                [extract | processing] ++
                  [parse_line, resolve_line, sizeof_line, io_size_line, io_data_line],
                "\n"
              )

            attr.terminator != nil ->
              # User type with terminator: read until terminator, apply processing, then parse substream
              consume = if attr.consume == false, do: "false", else: "true"
              include = if attr.include == true, do: "true", else: "false"

              extract =
                "{#{var}_data, rest} = Ksc.Stream.read_terminated(rest, #{attr.terminator}, #{consume}, #{include})"

              processing = build_data_processing(attr, "#{var}_data")

              parse_line =
                "{#{var}, _} = #{type_mod}.parse(#{var}_data, #{root_ref}, #{parent_ref}#{args_str})"

              resolve_line = "#{var} = #{type_mod}.resolve_instances(#{var}, #{var}_data)"
              Enum.join([extract | processing] ++ [parse_line, resolve_line], "\n")

            attr.size_eos == true ->
              """
              #{var}_data = rest
              {#{var}, _} = #{type_mod}.parse(rest, #{root_ref}, #{parent_ref}#{args_str})
              #{var} = #{type_mod}.resolve_instances(#{var}, #{var}_data)
              #{var} = Map.put(#{var}, :_io_data, #{var}_data)
              #{var} = Map.put(#{var}, :_io_size, byte_size(#{var}_data))
              rest = <<>>
              """
              |> String.trim()

            true ->
              # Check if child type has deferred instances (io: referencing _root)
              needs_deferred = has_root_io_instances?(base_type, spec)

              resolve_line =
                if needs_deferred do
                  ""
                else
                  "\n#{var} = #{type_mod}.resolve_instances(#{var}, io_data_)"
                end

              # For inline types, pass parent's io_size so child computes _io.pos/_io.size
              # relative to the parent stream (not the local substream)
              inline_parent =
                if parent_ref == "nil" do
                  parent_ref
                else
                  "Map.put(#{parent_ref}, :_io_size, byte_size(data))"
                end

              """
              {#{var}, rest} = #{type_mod}.parse(rest, #{root_ref}, #{inline_parent}#{args_str})#{resolve_line}
              """
              |> String.trim()
          end

        :switch ->
          cond do
            attr.size != nil ->
              # Sized switch: extract substream, switch-parse inside it
              size_expr = translate_expr(attr.size)

              switch_code =
                compile_switch_parse_inner(attr, endian, "#{var}_data", type_registry, spec)

              """
              size_#{attr.id} = #{size_expr}
              <<#{var}_data::binary-size(size_#{attr.id}), rest::binary>> = rest
              {#{var}, _} = #{switch_code}
              """
              |> String.trim()

            attr.size_eos == true ->
              # Size-eos switch: consume all remaining data, return raw bytes on no match
              switch_code =
                compile_switch_parse_inner(attr, endian, "#{var}_data", type_registry, spec)

              """
              #{var}_data = rest
              {#{var}, _} = #{switch_code}
              rest = <<>>
              """
              |> String.trim()

            true ->
              compile_switch_parse(attr, endian, var, type_registry, spec)
          end

        :bytes ->
          size_expr = translate_expr(attr.size)

          code =
            "size_#{attr.id} = #{size_expr}\n<<#{var}::binary-size(size_#{attr.id}), rest::binary>> = rest"

          maybe_apply_byte_processing(code, attr, var)

        :bytes_eos ->
          code = "#{var} = rest\nrest = <<>>"
          maybe_apply_byte_processing(code, attr, var)

        :str ->
          size_expr = translate_expr(attr.size)
          encoding = resolve_encoding(attr, spec)

          code =
            "size_#{attr.id} = #{size_expr}\n<<#{var}::binary-size(size_#{attr.id}), rest::binary>> = rest"

          code = maybe_apply_byte_processing(code, attr, var)
          maybe_apply_encoding(code, encoding, var)

        :str_eos ->
          encoding = resolve_encoding(attr, spec)
          code = "#{var} = rest\nrest = <<>>"
          code = maybe_apply_byte_processing(code, attr, var)
          maybe_apply_encoding(code, encoding, var)

        :strz ->
          encoding = resolve_encoding(attr, spec)
          consume = if attr.consume == false, do: "false", else: "true"
          include = if attr.include == true, do: "true", else: "false"

          if attr.size != nil do
            # Sized strz: extract size bytes, apply pad-right, then find null terminator within
            size_expr = translate_expr(attr.size)

            pad_step =
              if attr.pad_right != nil do
                "#{var} = Ksc.Stream.strip_pad_right(#{var}, #{attr.pad_right})\n"
              else
                ""
              end

            enc_str = if encoding, do: "\"#{encoding}\"", else: "nil"

            """
            size_#{attr.id} = #{size_expr}
            <<#{var}::binary-size(size_#{attr.id}), rest::binary>> = rest
            #{pad_step}{#{var}, _} = Ksc.Stream.read_strz_enc(#{var}, #{enc_str}, true, #{include})
            """
            |> String.trim()
          else
            if encoding && String.upcase(encoding) in ["UTF-16LE", "UTF-16BE"] do
              "{#{var}, rest} = Ksc.Stream.read_strz_enc(rest, \"#{encoding}\", #{consume}, #{include})"
            else
              code =
                if attr.consume == false or attr.include == true do
                  "{#{var}, rest} = Ksc.Stream.read_strz_enc(rest, nil, #{consume}, #{include})"
                else
                  "{#{var}, rest} = Ksc.Stream.read_strz(rest)"
                end

              maybe_apply_encoding(code, encoding, var)
            end
          end

        :terminated ->
          # Field with terminator but no size - scan for terminator
          consume = if attr.consume == false, do: "false", else: "true"
          include = if attr.include == true, do: "true", else: "false"
          encoding = resolve_encoding(attr, spec)

          code =
            "{#{var}, rest} = Ksc.Stream.read_terminated(rest, #{attr.terminator}, #{consume}, #{include})"

          maybe_apply_encoding(code, encoding, var)

        {:bit, size, bit_endian} ->
          bit_fn =
            case bit_endian do
              :le -> "read_bits_le"
              :be -> "read_bits_be"
              nil -> "read_bits"
            end

          code = "{#{var}, rest} = Ksc.Stream.#{bit_fn}(rest, #{size})"

          if size == 1 do
            code <> "\n#{var} = #{var} != 0"
          else
            code
          end

        _ ->
          "<<#{var}::#{match}, rest::binary>> = rest"
      end

    maybe_wrap_enum(code, attr, var)
  end

  defp compile_contents_parse(%AttrSpec{} = attr, var) do
    bytes = attr.contents
    size = length(bytes)
    byte_str = Enum.map(bytes, fn b -> Integer.to_string(b) end) |> Enum.join(", ")

    """
    <<#{var}::binary-size(#{size}), rest::binary>> = rest
    <<#{byte_str}>> = #{var}
    """
    |> String.trim()
  end

  defp compile_conditional_parse(%AttrSpec{} = attr, endian, var, type_registry, spec) do
    condition = translate_expr(attr.if_expr)
    inner_attr = %{attr | if_expr: nil}
    inner_code = compile_attr_parse(inner_attr, endian, type_registry, spec)

    """
    {#{var}, rest} = if #{condition} do
      #{Utils.indent(inner_code, 1)}
      {var_#{attr.id}, rest}
    else
      {nil, rest}
    end
    """
    |> String.trim()
  end

  defp compile_repeat_parse(%AttrSpec{} = attr, endian, var, type_registry, spec) do
    case attr.repeat do
      "expr" -> compile_repeat_expr(attr, endian, var, type_registry, spec)
      "eos" -> compile_repeat_eos(attr, endian, var, type_registry, spec)
      "until" -> compile_repeat_until(attr, endian, var, type_registry, spec)
    end
  end

  defp compile_repeat_expr(%AttrSpec{} = attr, endian, var, type_registry, spec) do
    count = translate_expr(attr.repeat_expr)
    inner_attr = %{attr | repeat: nil, repeat_expr: nil, if_expr: nil}
    inner_code = compile_simple_parse(inner_attr, endian, "item", type_registry, spec)
    inner_code = String.replace(inner_code, "var_#{attr.id}", "item")

    # If inner code passes result_so_far as parent, update it with accumulated items
    update_parent =
      if String.contains?(inner_code, "result_so_far") do
        "result_so_far = Map.put(result_so_far, :#{attr.id}, acc)\n    root_ = if(root_is_self_, do: result_so_far, else: root_)\n    "
      else
        ""
      end

    # Check if inner code uses _index
    needs_index = String.contains?(inner_code, "var__index")

    if spec.ks_debug do
      if needs_index do
        """
        {#{var}, rest} = try do
          Enum.reduce(Enum.with_index(1..max(#{count}, 0)//1), {[], rest}, fn {_, var__index}, {acc, rest} ->
            try do
              #{update_parent}#{Utils.indent(inner_code, 2)}
              {[item | acc], rest}
            rescue
              _ ->
                partial = Process.get(:_kaitai_debug_partial)
                Process.put(:_kaitai_debug_partial, nil)
                Process.put(:_kaitai_debug_rest, nil)
                if partial != nil do
                  throw({:partial_array, [partial | acc], rest})
                else
                  throw({:partial_array, acc, rest})
                end
            end
          end)
        catch
          {:partial_array, partial, partial_rest} -> {partial, partial_rest}
        end
        #{var} = Enum.reverse(#{var})
        """
        |> String.trim()
      else
        """
        {#{var}, rest} = try do
          Enum.reduce(1..max(#{count}, 0)//1, {[], rest}, fn _, {acc, rest} ->
            try do
              #{update_parent}#{Utils.indent(inner_code, 2)}
              {[item | acc], rest}
            rescue
              _ ->
                partial = Process.get(:_kaitai_debug_partial)
                Process.put(:_kaitai_debug_partial, nil)
                Process.put(:_kaitai_debug_rest, nil)
                if partial != nil do
                  throw({:partial_array, [partial | acc], rest})
                else
                  throw({:partial_array, acc, rest})
                end
            end
          end)
        catch
          {:partial_array, partial, partial_rest} -> {partial, partial_rest}
        end
        #{var} = Enum.reverse(#{var})
        """
        |> String.trim()
      end
    else
      if needs_index do
        """
        {#{var}, rest} = Enum.reduce(Enum.with_index(1..max(#{count}, 0)//1), {[], rest}, fn {_, var__index}, {acc, rest} ->
          #{update_parent}#{Utils.indent(inner_code, 1)}
          {[item | acc], rest}
        end)
        #{var} = Enum.reverse(#{var})
        """
        |> String.trim()
      else
        """
        {#{var}, rest} = Enum.reduce(1..max(#{count}, 0)//1, {[], rest}, fn _, {acc, rest} ->
          #{update_parent}#{Utils.indent(inner_code, 1)}
          {[item | acc], rest}
        end)
        #{var} = Enum.reverse(#{var})
        """
        |> String.trim()
      end
    end
  end

  defp compile_repeat_eos(%AttrSpec{} = attr, endian, var, type_registry, spec) do
    inner_attr = %{attr | repeat: nil, repeat_expr: nil, if_expr: nil}

    # Check if inner type is a bit type - needs special bit-aware repeat
    case type_to_pattern(inner_attr.type, endian, inner_attr, type_registry, spec) do
      {_, {:bit, bit_size, bit_endian}} ->
        bit_fn =
          case bit_endian do
            :le -> "read_bits_le"
            :be -> "read_bits_be"
            nil -> "read_bits_be"
          end

        """
        {#{var}, rest} = Ksc.Stream.repeat_eos_bits(rest, #{bit_size}, &Ksc.Stream.#{bit_fn}/2)
        """
        |> String.trim()

      _ ->
        inner_code = compile_simple_parse(inner_attr, endian, "item", type_registry, spec)
        inner_code = String.replace(inner_code, "var_#{attr.id}", "item")

        # Check if inner code uses _index
        needs_index = String.contains?(inner_code, "var__index")

        if needs_index do
          """
          {#{var}, rest} = Ksc.Stream.repeat_eos_idx(rest, fn rest, var__index ->
            #{Utils.indent(inner_code, 1)}
            {item, rest}
          end)
          """
          |> String.trim()
        else
          """
          {#{var}, rest} = Ksc.Stream.repeat_eos(rest, fn rest ->
            #{Utils.indent(inner_code, 1)}
            {item, rest}
          end)
          """
          |> String.trim()
        end
    end
  end

  defp compile_repeat_until(%AttrSpec{} = attr, endian, var, type_registry, spec) do
    inner_attr = %{attr | repeat: nil, repeat_expr: nil, repeat_until: nil, if_expr: nil}
    inner_code = compile_simple_parse(inner_attr, endian, "item", type_registry, spec)
    inner_code = String.replace(inner_code, "var_#{attr.id}", "item")
    condition = translate_expr_for_repeat_until(attr.repeat_until)

    needs_index = String.contains?(inner_code, "var__index")
    # Check if condition references io_pos/io_size which aren't in the condition lambda scope
    needs_io_in_condition =
      String.contains?(condition, "io_pos") or String.contains?(condition, "io_size")

    if needs_io_in_condition do
      # When condition needs IO state, evaluate it inside the parse lambda
      # and use repeat_until_check variant that receives done flag from parse fn
      if needs_index do
        """
        {#{var}, rest} = Ksc.Stream.repeat_until_check_idx(rest, fn rest, var__index ->
          #{Utils.indent(inner_code, 1)}
          io_pos_done_ = io_size - byte_size(rest)
          done = #{String.replace(condition, "io_pos", "io_pos_done_")}
          {item, rest, done}
        end)
        """
        |> String.trim()
      else
        """
        {#{var}, rest} = Ksc.Stream.repeat_until_check(rest, fn rest ->
          #{Utils.indent(inner_code, 1)}
          io_pos_done_ = io_size - byte_size(rest)
          done = #{String.replace(condition, "io_pos", "io_pos_done_")}
          {item, rest, done}
        end)
        """
        |> String.trim()
      end
    else
      if needs_index do
        """
        {#{var}, rest} = Ksc.Stream.repeat_until_idx(rest, fn rest, var__index ->
          #{Utils.indent(inner_code, 1)}
          {item, rest}
        end, fn item, _acc -> #{condition} end)
        """
        |> String.trim()
      else
        """
        {#{var}, rest} = Ksc.Stream.repeat_until(rest, fn rest ->
          #{Utils.indent(inner_code, 1)}
          {item, rest}
        end, fn item, _acc -> #{condition} end)
        """
        |> String.trim()
      end
    end
  end

  defp compile_switch_parse(%AttrSpec{} = attr, endian, var, type_registry, spec) do
    inner = compile_switch_parse_inner(attr, endian, "rest", type_registry, spec)

    """
    {#{var}, rest} = #{inner}
    """
    |> String.trim()
  end

  defp compile_switch_parse_inner(%AttrSpec{} = attr, endian, data_var, type_registry, spec) do
    %{"switch-on" => switch_expr, "cases" => cases} = attr.type
    switch_val = translate_expr(switch_expr)

    case_clauses =
      Enum.map(cases, fn {case_key, case_type} ->
        case_val = translate_case_key(case_key)
        inner_attr = %{attr | type: case_type, if_expr: nil, repeat: nil, size: nil}
        inner_code = compile_simple_parse(inner_attr, endian, "switch_val", type_registry, spec)
        # Replace "rest" references with our data variable
        inner_code =
          if data_var != "rest" do
            String.replace(inner_code, "rest", data_var)
          else
            inner_code
          end

        """
          #{case_val} ->
            #{Utils.indent(inner_code, 3)}
            {switch_val, #{data_var}}
        """
        |> String.trim_trailing()
      end)
      |> Enum.join("\n")

    # Add a catch-all if there's no "_" case
    has_default = Enum.any?(cases, fn {k, _} -> k == "_" end)

    case_clauses =
      if has_default do
        case_clauses
      else
        # For sized switches (data_var != "rest"), return raw bytes on no match
        # For non-sized switches, return nil
        if data_var != "rest" do
          case_clauses <> "\n  _ ->\n      {#{data_var}, #{data_var}}"
        else
          case_clauses <> "\n  _ ->\n      {nil, #{data_var}}"
        end
      end

    """
    case #{switch_val} do
    #{case_clauses}
    end
    """
    |> String.trim()
  end

  # Translate case keys - handle enum references like "enum_name::value"
  defp translate_case_key(key) when is_binary(key) do
    cond do
      String.contains?(key, "::") ->
        # Enum reference: "enum_name::value" -> :value
        parts = String.split(key, "::")
        value = List.last(parts)
        ":#{value}"

      key == "_" ->
        "_"

      key == "true" ->
        "true"

      key == "false" ->
        "false"

      String.starts_with?(key, "\"") ->
        key

      true ->
        translate_expr(key)
    end
  end

  defp translate_case_key(key) when is_integer(key), do: Integer.to_string(key)
  defp translate_case_key(key), do: to_string(key)

  defp compile_instances(instances, endian, type_registry, spec, eager_instances) do
    if map_size(instances) == 0 do
      # Always generate resolve_instances (no-op for types without instances)
      ["def resolve_instances(result, _root_data), do: result"]
    else
      resolve_fn =
        compile_resolve_instances(instances, endian, type_registry, spec, eager_instances)

      [resolve_fn]
    end
  end

  defp compile_resolve_instances(instances, endian, type_registry, spec, eager_instances) do
    # Convert switch endian to :dynamic for instance compilation
    effective_endian =
      case endian do
        {:switch, _, _} -> :dynamic
        other -> other
      end

    # Topological sort: resolve instances in dependency order
    sorted_instances = topological_sort_instances(instances)
    # Skip eagerly-computed positional instances (they're already set in parse)
    sorted_instances =
      Enum.reject(sorted_instances, fn {name, _inst} ->
        name in eager_instances
      end)

    assignments =
      Enum.map(sorted_instances, fn {name, %InstanceSpec{} = inst} ->
        code =
          cond do
            inst.value != nil ->
              expr = translate_expr_for_instance(inst.value)
              # Apply enum conversion if instance has enum annotation
              if inst.enum != nil do
                enum_ref =
                  if String.contains?(inst.enum, "::") do
                    parts = String.split(inst.enum, "::")
                    enum_id = List.last(parts)

                    type_path =
                      Enum.slice(parts, 0..-2//1)
                      |> Enum.map(&Utils.to_module_name/1)
                      |> Enum.join(".")

                    "#{type_path}.enum_#{enum_id}()"
                  else
                    "@enum_#{inst.enum}"
                  end

                "inst_val = #{expr}\nresult = Map.put(result, :#{name}, Map.get(#{enum_ref}, inst_val, inst_val))"
              else
                "result = Map.put(result, :#{name}, #{expr})"
              end

            inst.pos != nil ->
              pos_expr = translate_expr_for_instance(inst.pos)
              compile_parse_instance(name, inst, pos_expr, effective_endian, type_registry, spec)

            inst.type != nil and inst.size != nil ->
              size_expr = translate_expr_for_instance(inst.size)

              compile_sized_parse_instance(
                name,
                inst,
                size_expr,
                effective_endian,
                type_registry,
                spec
              )

            inst.type != nil and inst.size_eos == true ->
              # Type with size-eos: parse from current data
              type_mod = resolve_type_module(inst.type, type_registry, spec)

              """
              {inst_val, _} = #{type_mod}.parse(root_data, result)
              result = Map.put(result, :#{name}, inst_val)
              """
              |> String.trim()

            true ->
              nil
          end

        # Wrap in conditional if needed
        if code != nil and inst.if_expr != nil do
          condition = translate_expr_for_instance(inst.if_expr)

          """
          result = if #{condition} do
            #{code}
            result
          else
            Map.put(result, :#{name}, nil)
          end
          """
          |> String.trim()
        else
          code
        end
      end)
      |> Enum.reject(&is_nil/1)

    # Check if root_ needs refreshing after mutations
    needs_root_refresh =
      Enum.any?(sorted_instances, fn {_, inst} ->
        inst.pos != nil and inst.type != nil
      end)

    assignments =
      if needs_root_refresh do
        # Insert root_ refresh after each instance that mutates result
        Enum.map(assignments, fn code ->
          code <> "\nroot_ = if result[:_root] != nil, do: result, else: root_"
        end)
      else
        assignments
      end
      |> Enum.join("\n")

    if assignments == "" do
      "def resolve_instances(result, _root_data), do: result"
    else
      # Add io_size/io_pos initialization independently if referenced (use word boundary to avoid _io_pos/_io_size)
      needs_io_size = Regex.match?(~r/(?<![_\w])io_size\b/, assignments)
      needs_io_pos = Regex.match?(~r/(?<![_\w])io_pos\b/, assignments)

      io_size_init = if needs_io_size, do: "io_size = byte_size(root_data)", else: nil
      io_pos_init = if needs_io_pos, do: "io_pos = result[:_io_pos] || 0", else: nil

      # Extract parent_ and root_ from result if instances reference them (use word boundary to avoid root_data, :_root)
      needs_parent = String.contains?(assignments, "parent_")
      needs_root = Regex.match?(~r/(?<![_:\w])root_(?!data)/, assignments) or needs_root_refresh
      needs_is_le = String.contains?(assignments, "var__is_le")
      parent_init = if needs_parent, do: "parent_ = result[:_parent]", else: nil
      root_init = if needs_root, do: "root_ = result[:_root] || result", else: nil
      is_le_init = if needs_is_le, do: "var__is_le = result[:_is_le]", else: nil

      # Suppress unused variable warnings for variables that may be set but not read after the last assignment
      suppress =
        [
          if(root_init, do: "_ = root_"),
          if(io_pos_init, do: "_ = io_pos"),
          if(io_size_init, do: "_ = io_size")
        ]
        |> Enum.reject(&is_nil/1)
        |> Enum.join("\n")

      suppress_line = if suppress != "", do: suppress, else: nil

      body =
        [
          io_size_init,
          io_pos_init,
          parent_init,
          root_init,
          is_le_init,
          assignments,
          suppress_line
        ]
        |> Enum.reject(&is_nil/1)
        |> Enum.join("\n")

      root_data_param =
        if String.contains?(body, "root_data"), do: "root_data", else: "_root_data"

      """
      def resolve_instances(result, #{root_data_param}) do
        #{body}
        result
      end
      """
      |> String.trim()
    end
  end

  defp compile_parse_instance(name, inst, pos_expr, endian, type_registry, spec) do
    # Handle repeat instances: parse from pos, repeating N times
    if inst.repeat == "expr" and inst.repeat_expr != nil do
      compile_repeat_parse_instance(name, inst, pos_expr, endian, type_registry, spec)
    else
      compile_single_parse_instance(name, inst, pos_expr, endian, type_registry, spec)
    end
  end

  defp compile_repeat_parse_instance(name, inst, pos_expr, _endian, type_registry, spec) do
    count_expr = translate_expr_for_instance(inst.repeat_expr)

    io_source =
      if inst.io != nil do
        translate_io_expr(inst.io)
      else
        "root_data"
      end

    remaining_expr =
      "binary_part(#{io_source}, #{pos_expr}, byte_size(#{io_source}) - #{pos_expr})"

    if inst.type != nil do
      {base_type, _type_args} = parse_type_args(inst.type)
      type_mod = resolve_type_module(base_type, type_registry, spec)
      has_insts = has_instances_for_type?(base_type, spec)

      if inst.size != nil do
        size_expr = translate_expr_for_instance(inst.size)

        resolve_line =
          if has_insts,
            do: "\n      item = #{type_mod}.resolve_instances(item, item_data)",
            else: ""

        """
        inst_count_ = #{count_expr}
        inst_size_ = #{size_expr}
        inst_items = Enum.reduce(1..max(inst_count_, 0)//1, {[], #{remaining_expr}}, fn _, {acc, inst_rest} ->
          <<item_data::binary-size(inst_size_), inst_rest::binary>> = inst_rest
          {item, _} = #{type_mod}.parse(item_data, result)#{resolve_line}
          {[item | acc], inst_rest}
        end) |> elem(0) |> Enum.reverse()
        result = Map.put(result, :#{name}, inst_items)
        """
        |> String.trim()
      else
        resolve_line =
          if has_insts,
            do: "\n      item = #{type_mod}.resolve_instances(item, inst_rest)",
            else: ""

        """
        inst_count_ = #{count_expr}
        inst_items = Enum.reduce(1..max(inst_count_, 0)//1, {[], #{remaining_expr}}, fn _, {acc, inst_rest} ->
          {item, inst_rest} = #{type_mod}.parse(inst_rest, result)#{resolve_line}
          {[item | acc], inst_rest}
        end) |> elem(0) |> Enum.reverse()
        result = Map.put(result, :#{name}, inst_items)
        """
        |> String.trim()
      end
    else
      # No type - read raw bytes of given size
      size_expr = translate_expr_for_instance(inst.size || "1")

      """
      inst_count_ = #{count_expr}
      inst_size_ = #{size_expr}
      inst_items = Enum.reduce(1..max(inst_count_, 0)//1, {[], #{remaining_expr}}, fn _, {acc, inst_rest} ->
        <<item::binary-size(inst_size_), inst_rest::binary>> = inst_rest
        {[item | acc], inst_rest}
      end) |> elem(0) |> Enum.reverse()
      result = Map.put(result, :#{name}, inst_items)
      """
      |> String.trim()
    end
  end

  defp compile_single_parse_instance(name, inst, pos_expr, endian, type_registry, spec) do
    # Determine which IO stream to read from
    io_source =
      if inst.io != nil do
        translate_io_expr(inst.io)
      else
        "root_data"
      end

    # Determine how much to read
    data_expr =
      if inst.size != nil do
        size_expr = translate_expr_for_instance(inst.size)
        "binary_part(#{io_source}, #{pos_expr}, #{size_expr})"
      else
        "binary_part(#{io_source}, #{pos_expr}, byte_size(#{io_source}) - #{pos_expr})"
      end

    if inst.type == nil do
      # No type - just read bytes
      """
      inst_val = #{data_expr}
      result = Map.put(result, :#{name}, inst_val)
      """
      |> String.trim()
    else
      # Handle switch-on types in instances
      if is_map(inst.type) and Map.has_key?(inst.type, "switch-on") do
        compile_switch_instance(name, inst, data_expr, io_source, endian, type_registry, spec)
      else
        # Parse type args for parameterized types
        {base_type, type_args} = parse_type_args(inst.type)

        {_match, type_info} =
          type_to_pattern(
            base_type,
            endian,
            %AttrSpec{size: inst.size, size_eos: inst.size_eos},
            type_registry,
            spec
          )

        inst_args_str =
          if type_args != [] do
            ", " <> Enum.map_join(type_args, ", ", &translate_expr_for_instance/1)
          else
            ""
          end

        case type_info do
          :user_type ->
            type_mod = resolve_type_module(base_type, type_registry, spec)
            # Call resolve_instances unless self-referential (prevents infinite recursion)
            is_self_ref = base_type == spec.id

            if is_self_ref do
              """
              inst_data = #{data_expr}
              {inst_val, _} = #{type_mod}.parse(inst_data, result, result#{inst_args_str})
              result = Map.put(result, :#{name}, inst_val)
              """
              |> String.trim()
            else
              # For sized instances, resolve_instances gets the substream (inst_data)
              # since the child type's _io is the substream.
              # For unsized instances, resolve_instances gets the parent's io_source
              # since the child type's _io is the parent's stream.
              resolve_data = if inst.size != nil, do: "inst_data", else: io_source

              """
              inst_data = #{data_expr}
              {inst_val, _} = #{type_mod}.parse(inst_data, result, result#{inst_args_str})
              inst_val = #{type_mod}.resolve_instances(inst_val, #{resolve_data})
              result = Map.put(result, :#{name}, inst_val)
              """
              |> String.trim()
            end

          :primitive ->
            if endian == :dynamic and is_endian_dependent_type?(base_type) do
              {le_match, _} = type_to_pattern(base_type, :le, %AttrSpec{}, type_registry, spec)
              {be_match, _} = type_to_pattern(base_type, :be, %AttrSpec{}, type_registry, spec)

              """
              inst_data = #{data_expr}
              inst_val = if var__is_le do
                <<v::#{le_match}, _::binary>> = inst_data
                v
              else
                <<v::#{be_match}, _::binary>> = inst_data
                v
              end
              #{maybe_wrap_enum_inst(inst, "inst_val")}
              result = Map.put(result, :#{name}, inst_val)
              """
              |> String.trim()
            else
              {match, _} = type_to_pattern(base_type, endian, %AttrSpec{}, type_registry, spec)

              """
              inst_data = #{data_expr}
              <<inst_val::#{match}, _::binary>> = inst_data
              #{maybe_wrap_enum_inst(inst, "inst_val")}
              result = Map.put(result, :#{name}, inst_val)
              """
              |> String.trim()
            end

          :strz ->
            """
            inst_data = #{data_expr}
            {inst_val, _} = Ksc.Stream.read_strz(inst_data)
            result = Map.put(result, :#{name}, inst_val)
            """
            |> String.trim()

          _ ->
            # Covers :str, :str_eos, :bytes, :raw, and other types
            """
            inst_val = #{data_expr}
            result = Map.put(result, :#{name}, inst_val)
            """
            |> String.trim()
        end
      end

      # end if is_map switch-on
    end
  end

  defp compile_switch_instance(name, inst, data_expr, _io_source, endian, type_registry, spec) do
    %{"switch-on" => switch_expr, "cases" => cases} = inst.type
    switch_val = translate_expr_for_instance(switch_expr)

    case_clauses =
      Enum.map(cases, fn {case_key, case_type} ->
        case_val = translate_case_key(case_key)
        {case_base, case_args} = parse_type_args(case_type)
        {_, case_type_info} = type_to_pattern(case_base, endian, %AttrSpec{}, type_registry, spec)

        args_str =
          if case_args != [] do
            ", " <> Enum.map_join(case_args, ", ", &translate_expr_for_instance/1)
          else
            ""
          end

        case case_type_info do
          :user_type ->
            type_mod = resolve_type_module(case_base, type_registry, spec)
            has_insts = has_instances_for_type?(case_base, spec)

            resolve =
              if has_insts,
                do: "\n    inst_val = #{type_mod}.resolve_instances(inst_val, inst_data)",
                else: ""

            "#{case_val} ->\n    {inst_val, _} = #{type_mod}.parse(inst_data, result, result#{args_str})#{resolve}\n    inst_val"

          _ ->
            "#{case_val} ->\n    inst_data"
        end
      end)
      |> Enum.join("\n  ")

    has_default = Enum.any?(cases, fn {k, _} -> k == "_" end)
    default_clause = if not has_default, do: "\n  _ ->\n    inst_data", else: ""

    """
    inst_data = #{data_expr}
    inst_val = case #{switch_val} do
      #{case_clauses}#{default_clause}
    end
    result = Map.put(result, :#{name}, inst_val)
    """
    |> String.trim()
  end

  defp has_instances_for_type?(type_name, spec) when is_binary(type_name) do
    case Map.get(spec.types, type_name) do
      %ClassSpec{instances: instances} when map_size(instances) > 0 -> true
      _ -> false
    end
  end

  defp has_root_io_instances?(type_name, spec) when is_binary(type_name) do
    case Map.get(spec.types, type_name) do
      %ClassSpec{instances: instances} when map_size(instances) > 0 ->
        Enum.any?(instances, fn {_, inst} ->
          inst.io != nil and String.contains?(to_string(inst.io), "_root")
        end)

      _ ->
        false
    end
  end

  defp maybe_wrap_enum_inst(%InstanceSpec{enum: nil}, _var), do: ""

  defp maybe_wrap_enum_inst(%InstanceSpec{enum: enum_name}, var) do
    if String.contains?(enum_name, "::") do
      parts = String.split(enum_name, "::")
      enum_id = List.last(parts)
      "#{var} = Map.get(@enum_#{enum_id}, #{var}, #{var})"
    else
      "#{var} = Map.get(@enum_#{enum_name}, #{var}, #{var})"
    end
  end

  defp compile_sized_parse_instance(name, inst, size_expr, endian, type_registry, spec) do
    {base_type, type_args} = parse_type_args(inst.type)

    {_match, type_info} =
      type_to_pattern(base_type, endian, %AttrSpec{size: inst.size}, type_registry, spec)

    inst_args_str =
      if type_args != [] do
        ", " <> Enum.map_join(type_args, ", ", &translate_expr_for_instance/1)
      else
        ""
      end

    case type_info do
      :user_type ->
        type_mod = resolve_type_module(base_type, type_registry, spec)

        """
        inst_size = #{size_expr}
        <<inst_data::binary-size(inst_size), _::binary>> = root_data
        {inst_val, _} = #{type_mod}.parse(inst_data, result, result#{inst_args_str})
        result = Map.put(result, :#{name}, inst_val)
        """
        |> String.trim()

      :primitive ->
        {match, _} = type_to_pattern(base_type, endian, %AttrSpec{}, type_registry, spec)

        """
        <<inst_val::#{match}, _::binary>> = root_data
        result = Map.put(result, :#{name}, inst_val)
        """
        |> String.trim()

      _ ->
        """
        inst_size = #{size_expr}
        <<inst_val::binary-size(inst_size), _::binary>> = root_data
        result = Map.put(result, :#{name}, inst_val)
        """
        |> String.trim()
    end
  end

  defp type_to_pattern(nil, _endian, attr, _type_registry, _spec) do
    cond do
      attr.size != nil -> {"", :bytes}
      attr.size_eos == true and Map.get(attr, :terminator) != nil -> {"", :bytes_eos}
      attr.size_eos == true -> {"", :bytes_eos}
      Map.get(attr, :terminator) != nil -> {"", :terminated}
      true -> {"binary", :raw}
    end
  end

  defp type_to_pattern(type, endian, attr, type_registry, spec) when is_binary(type) do
    # Strip type args for pattern matching
    {base_type, _args} = parse_type_args(type)

    cond do
      # Bit types: b1 through b64, also bNbe and bNle
      Regex.match?(~r/^b\d+(be|le)?$/, base_type) ->
        bit_str = Regex.run(~r/^b(\d+)(be|le)?$/, base_type)
        bit_size = Enum.at(bit_str, 1) |> String.to_integer()

        bit_endian =
          case Enum.at(bit_str, 2) do
            "le" -> :le
            "be" -> :be
            nil -> nil
          end

        {"", {:bit, bit_size, bit_endian}}

      true ->
        case base_type do
          "u1" ->
            {"unsigned-integer-size(8)", :primitive}

          "s1" ->
            {"signed-integer-size(8)", :primitive}

          "u2" ->
            {"unsigned-integer-#{endian_str(endian)}-size(16)", :primitive}

          "u2le" ->
            {"unsigned-integer-little-size(16)", :primitive}

          "u2be" ->
            {"unsigned-integer-big-size(16)", :primitive}

          "s2" ->
            {"signed-integer-#{endian_str(endian)}-size(16)", :primitive}

          "s2le" ->
            {"signed-integer-little-size(16)", :primitive}

          "s2be" ->
            {"signed-integer-big-size(16)", :primitive}

          "u4" ->
            {"unsigned-integer-#{endian_str(endian)}-size(32)", :primitive}

          "u4le" ->
            {"unsigned-integer-little-size(32)", :primitive}

          "u4be" ->
            {"unsigned-integer-big-size(32)", :primitive}

          "s4" ->
            {"signed-integer-#{endian_str(endian)}-size(32)", :primitive}

          "s4le" ->
            {"signed-integer-little-size(32)", :primitive}

          "s4be" ->
            {"signed-integer-big-size(32)", :primitive}

          "u8" ->
            {"unsigned-integer-#{endian_str(endian)}-size(64)", :primitive}

          "u8le" ->
            {"unsigned-integer-little-size(64)", :primitive}

          "u8be" ->
            {"unsigned-integer-big-size(64)", :primitive}

          "s8" ->
            {"signed-integer-#{endian_str(endian)}-size(64)", :primitive}

          "s8le" ->
            {"signed-integer-little-size(64)", :primitive}

          "s8be" ->
            {"signed-integer-big-size(64)", :primitive}

          "f4" ->
            {"float-#{endian_str(endian)}-size(32)", :primitive}

          "f4le" ->
            {"float-little-size(32)", :primitive}

          "f4be" ->
            {"float-big-size(32)", :primitive}

          "f8" ->
            {"float-#{endian_str(endian)}-size(64)", :primitive}

          "f8le" ->
            {"float-little-size(64)", :primitive}

          "f8be" ->
            {"float-big-size(64)", :primitive}

          "str" ->
            cond do
              attr.size != nil -> {"", :str}
              Map.get(attr, :terminator) != nil -> {"", :terminated}
              attr.size_eos == true -> {"", :str_eos}
              true -> {"", :str_eos}
            end

          "strz" ->
            {"", :strz}

          _ ->
            if is_user_type?(type, type_registry, spec) or
                 Regex.match?(~r/^[a-z_][a-z0-9_]*$/, base_type) do
              {"", :user_type}
            else
              {"binary", :raw}
            end
        end
    end
  end

  defp type_to_pattern(%{"switch-on" => _, "cases" => _}, _endian, _attr, _type_registry, _spec) do
    {"", :switch}
  end

  defp is_user_type?(type, type_registry, spec) do
    # Strip args from type reference
    {base_type, _args} = parse_type_args(type)
    # Handle :: path separator (e.g., "subtype_a::subtype_cc")
    if String.contains?(base_type, "::") do
      true
    else
      # Check local types, type registry, and imports
      Map.has_key?(type_registry, base_type) or
        Map.has_key?(spec.types, base_type) or
        base_type in (spec.imports || []) or
        Enum.any?(spec.imports || [], fn imp ->
          # Import could be "common/vlq" but type ref is just "vlq_base128_le"
          String.ends_with?(imp, "/#{base_type}") or imp == base_type
        end)
    end
  end

  defp is_cross_module_type?(type, spec) do
    if String.contains?(type, "::") do
      first_part = type |> String.split("::") |> List.first()

      Enum.any?(spec.imports || [], fn imp ->
        imp_name =
          if String.contains?(imp, "/"), do: imp |> String.split("/") |> List.last(), else: imp

        imp_name == first_part
      end)
    else
      false
    end
  end

  defp resolve_type_module(type, type_registry, spec) do
    if String.contains?(type, "::") do
      # Convert path like "subtype_a::subtype_cc" to "SubtypeA.SubtypeCc"
      parts = String.split(type, "::")
      Enum.map(parts, &Utils.to_module_name/1) |> Enum.join(".")
    else
      cond do
        Map.has_key?(spec.types, type) ->
          Utils.to_module_name(type)

        Map.has_key?(type_registry, type) ->
          Map.get(type_registry, type)

        true ->
          Utils.to_module_name(type)
      end
    end
  end

  defp compile_is_le_switch(switch_on, cases) do
    switch_expr = translate_expr(switch_on)

    case_clauses =
      Enum.map(cases, fn {case_key, endian_val} ->
        case_pattern = translate_endian_case_key(case_key)
        is_le = endian_val == :le
        "  #{case_pattern} -> #{is_le}"
      end)
      |> Enum.join("\n")

    # Add default if no _ case
    has_default = Enum.any?(cases, fn {k, _} -> k == "_" end)

    case_clauses =
      if has_default do
        case_clauses
      else
        case_clauses <> "\n  _ -> false"
      end

    "var__is_le = case #{switch_expr} do\n#{case_clauses}\nend"
  end

  defp translate_endian_case_key("_"), do: "_"
  defp translate_endian_case_key(key), do: translate_expr(String.trim(key))

  defp endian_str(:le), do: "little"
  defp endian_str(:be), do: "big"
  defp endian_str(nil), do: "big"
  defp endian_str(:dynamic), do: "big"
  defp endian_str({:switch, _, _}), do: "big"

  defp maybe_wrap_enum(code, %AttrSpec{enum: nil}, _var), do: code

  defp maybe_wrap_enum(code, %AttrSpec{enum: enum_name}, var) do
    # Handle cross-type enum references like "container1::animal"
    if String.contains?(enum_name, "::") do
      parts = String.split(enum_name, "::")

      type_path =
        Enum.slice(parts, 0..-2//1) |> Enum.map(&Utils.to_module_name/1) |> Enum.join(".")

      enum_id = List.last(parts)
      # Reference the enum in the specific type module
      code <> "\n#{var} = Map.get(#{type_path}.enum_#{enum_id}(), #{var}, #{var})"
    else
      code <> "\n#{var} = Map.get(@enum_#{enum_name}, #{var}, #{var})"
    end
  end

  defp maybe_apply_byte_processing(code, %AttrSpec{} = attr, var) do
    code =
      cond do
        # Both terminator and pad_right: combined handling (pad only when no terminator found)
        attr.terminator != nil and attr.pad_right != nil and attr.pad_right != attr.terminator ->
          code <>
            "\n#{var} = Ksc.Stream.terminate_and_pad(#{var}, #{attr.terminator}, #{attr.include == true}, #{attr.pad_right})"

        # Terminator only (or pad == term)
        attr.terminator != nil ->
          code <>
            "\n#{var} = Ksc.Stream.terminate_at(#{var}, #{attr.terminator}, #{attr.include == true})"

        # Pad only
        attr.pad_right != nil ->
          code <> "\n#{var} = Ksc.Stream.strip_pad_right(#{var}, #{attr.pad_right})"

        true ->
          code
      end

    maybe_apply_process(code, attr, var)
  end

  defp maybe_apply_process(code, %AttrSpec{process: nil}, _var), do: code

  defp maybe_apply_process(code, %AttrSpec{process: process}, var) when is_binary(process) do
    code <> "\n" <> build_process_step(process, var)
  end

  defp maybe_apply_process(code, _attr, _var), do: code

  defp compile_enums(enums) when map_size(enums) == 0 do
    {"", ""}
  end

  defp compile_enums(enums) do
    enum_defs =
      Enum.map(enums, fn {name, %{values: values}} ->
        map_str =
          Enum.map(values, fn {k, v} -> "#{k} => :#{v}" end)
          |> Enum.join(", ")

        "@enum_#{name} %{#{map_str}}\ndef enum_#{name}(), do: @enum_#{name}"
      end)
      |> Enum.join("\n")

    # Generate combined reverse map (atom -> integer) for to_i support
    reverse_entries =
      Enum.flat_map(enums, fn {_name, %{values: values}} ->
        Enum.map(values, fn {k, v} -> "#{v}: #{k}" end)
      end)
      |> Enum.join(", ")

    {enum_defs, "@kaitai_enum_reverse %{#{reverse_entries}}"}
  end

  defp translate_expr(nil), do: "nil"

  defp translate_expr(expr) when is_binary(expr) do
    Ksc.Expression.translate(escape_elixir_interpolation(expr))
  end

  defp translate_expr(val) when is_integer(val), do: Integer.to_string(val)
  defp translate_expr(val) when is_float(val), do: Float.to_string(val)

  # Instance expressions use result[:field] instead of var_field
  defp translate_expr_for_instance(nil), do: "nil"

  defp translate_expr_for_instance(expr) when is_binary(expr) do
    Ksc.Expression.translate_for_instance(escape_elixir_interpolation(expr))
  end

  defp translate_expr_for_instance(val) when is_integer(val), do: Integer.to_string(val)
  defp translate_expr_for_instance(val) when is_float(val), do: Float.to_string(val)

  # Translate io: expression to get the binary data source.
  # mode: :instance (result[:field]) or :parse (var_field)
  defp translate_io_expr(io_str, mode \\ :instance) when is_binary(io_str) do
    {parent_access, fallback, expr_fn} =
      case mode do
        :instance -> {"result[:_parent]", "root_data", &translate_expr_for_instance/1}
        :parse -> {"parent_", "data", &translate_expr/1}
      end

    cond do
      io_str == "_root._io" ->
        "(root_[:_io_data] || #{fallback})"

      io_str == "_parent._io" ->
        "(#{parent_access}[:_io_data] || #{fallback})"

      String.ends_with?(io_str, "._io") ->
        obj = String.slice(io_str, 0..-5//1)
        "(#{expr_fn.(obj)}[:_io_data] || #{fallback})"

      true ->
        fallback
    end
  end

  # repeat-until uses _ as the current item reference
  defp translate_expr_for_repeat_until(expr) when is_binary(expr) do
    Ksc.Expression.translate_for_repeat_until(escape_elixir_interpolation(expr))
  end

  defp collect_all_expressions(attrs) do
    Enum.flat_map(attrs, fn %AttrSpec{} = a ->
      [a.size, a.if_expr, a.repeat_expr, a.repeat_until, a.process] |> Enum.reject(&is_nil/1)
    end)
  end

  defp insert_io_pos_updates(body) do
    # Insert io_pos = io_size - byte_size(rest) before lines that use io_pos.
    # _io.pos represents the current stream position after the most recent read.
    # Inside bit runs (between bits_state init and align_to_byte), use the
    # bits_state's internal data instead of rest for accurate byte position.
    # Also replace (io_pos >= io_size) EOF check with bits-aware version in bit runs.
    lines = String.split(body, "\n")
    # Match io_pos as a standalone variable (not io_pos_done_ or _io_pos)
    io_pos_re = ~r/(?<![_\w])io_pos(?![_\w])/

    {result, _in_bits} =
      Enum.reduce(lines, {[], false}, fn line, {acc, in_bits} ->
        trimmed = String.trim(line)

        cond do
          String.starts_with?(trimmed, "bits_state = {0, 0, rest}") ->
            {acc ++ [line], true}

          String.starts_with?(trimmed, "rest = Ksc.Stream.align_to_byte(bits_state)") ->
            {acc ++ [line], false}

          Regex.match?(io_pos_re, line) and not String.starts_with?(trimmed, "io_pos =") and
              not String.starts_with?(trimmed, "io_size =") ->
            # In bit context, replace EOF check with bits-aware version
            line =
              if in_bits do
                String.replace(
                  line,
                  "(io_pos >= io_size)",
                  "(byte_size(elem(bits_state, 2)) == 0 and elem(bits_state, 1) == 0)"
                )
              else
                line
              end

            # After replacement, check if io_pos is still referenced
            if Regex.match?(io_pos_re, line) do
              pos_expr =
                if in_bits do
                  "io_pos = io_size - byte_size(elem(bits_state, 2))"
                else
                  "io_pos = io_size - byte_size(rest)"
                end

              # Skip inserting if the previous line is already an io_pos assignment (avoid redundant assignments)
              prev_is_io_pos =
                case List.last(acc) do
                  nil -> false
                  prev -> String.starts_with?(String.trim(prev), "io_pos =")
                end

              if prev_is_io_pos do
                # Replace the previous io_pos assignment with the new one
                {List.delete_at(acc, -1) ++ [pos_expr, line], in_bits}
              else
                {acc ++ [pos_expr, line], in_bits}
              end
            else
              # io_pos was fully replaced (e.g., bits-aware EOF check), no assignment needed
              {acc ++ [line], in_bits}
            end

          true ->
            {acc ++ [line], in_bits}
        end
      end)

    Enum.join(result, "\n")
  end

  # Parse type reference with optional arguments: "my_type(arg1, arg2)" -> {"my_type", ["arg1", "arg2"]}
  defp parse_type_args(type) when is_binary(type) do
    case Regex.run(~r/^([a-zA-Z_][a-zA-Z0-9_:]*)\((.+)\)$/, type) do
      [_, base_type, args_str] ->
        args = split_balanced_args(args_str)
        {base_type, args}

      nil ->
        {type, []}
    end
  end

  defp parse_type_args(type), do: {type, []}

  # Split on commas outside of parentheses, brackets, and braces
  defp split_balanced_args(str) do
    chars = String.graphemes(str)

    {args, current, _depth} =
      Enum.reduce(chars, {[], "", 0}, fn ch, {args, current, depth} ->
        case ch do
          c when c in ["(", "[", "{"] -> {args, current <> ch, depth + 1}
          c when c in [")", "]", "}"] -> {args, current <> ch, depth - 1}
          "," when depth == 0 -> {args ++ [String.trim(current)], "", 0}
          _ -> {args, current <> ch, depth}
        end
      end)

    args ++ [String.trim(current)]
  end

  # Build processing steps for data variable (term + pad combined, then process)
  defp build_data_processing(%AttrSpec{} = attr, data_var) do
    steps =
      cond do
        attr.terminator != nil and attr.pad_right != nil and attr.pad_right != attr.terminator ->
          [
            "#{data_var} = Ksc.Stream.terminate_and_pad(#{data_var}, #{attr.terminator}, #{attr.include == true}, #{attr.pad_right})"
          ]

        attr.terminator != nil ->
          [
            "#{data_var} = Ksc.Stream.terminate_at(#{data_var}, #{attr.terminator}, #{attr.include == true})"
          ]

        attr.pad_right != nil ->
          ["#{data_var} = Ksc.Stream.strip_pad_right(#{data_var}, #{attr.pad_right})"]

        true ->
          []
      end

    steps =
      if attr.process != nil do
        steps ++ [build_process_step(attr.process, data_var)]
      else
        steps
      end

    steps
  end

  defp build_process_step(process, var) when is_binary(process) do
    cond do
      Regex.match?(~r/^xor\(/, process) ->
        arg = extract_process_arg(process)
        "#{var} = Ksc.Stream.process_xor(#{var}, #{translate_expr(arg)})"

      process == "zlib" ->
        "#{var} = Ksc.Stream.process_zlib(#{var})"

      Regex.match?(~r/^rotate_left\(/, process) ->
        arg = extract_process_arg(process)
        "#{var} = Ksc.Stream.process_rotate_left(#{var}, #{translate_expr(arg)})"

      Regex.match?(~r/^rol\(/, process) ->
        arg = extract_process_arg(process)
        "#{var} = Ksc.Stream.process_rotate_left(#{var}, #{translate_expr(arg)})"

      Regex.match?(~r/^ror\(/, process) ->
        arg = extract_process_arg(process)
        "#{var} = Ksc.Stream.process_rotate_left(#{var}, 8 - (#{translate_expr(arg)}))"

      true ->
        # Custom process function
        {mod_name, args} = parse_custom_process(process)

        args_str =
          if args != [], do: ", " <> Enum.map_join(args, ", ", &translate_expr/1), else: ""

        "process = #{mod_name}.new(#{String.trim_leading(args_str, ", ")})\n" <>
          "#{var} = #{mod_name}.decode(process, #{var})"
    end
  end

  # Extract the argument from a process call like "xor(arg)" or "rol(complex(expr))"
  # by finding the first opening paren and matching the last closing paren
  defp extract_process_arg(process) do
    idx = :binary.match(process, "(") |> elem(0)
    inner = String.slice(process, (idx + 1)..-1//1)
    # Remove exactly the last closing paren
    last_paren = String.length(inner) - 1

    if String.at(inner, last_paren) == ")" do
      String.slice(inner, 0, last_paren)
    else
      inner
    end
  end

  # Parse a custom process string like "my_custom_fx(7, true, [0x20])" or "custom_fx_no_args"
  # Returns {ModuleName, [arg_strings]}
  defp parse_custom_process(process) do
    case Regex.run(~r/^([a-zA-Z][a-zA-Z0-9_.]*)\((.*)\)$/s, process) do
      [_, name, args_str] ->
        mod_name =
          name
          |> String.split(".")
          |> Enum.map(&Macro.camelize/1)
          |> Enum.join(".")

        args = split_balanced_args(args_str)
        {mod_name, args}

      nil ->
        # No args: "custom_fx_no_args"
        mod_name =
          process
          |> String.trim()
          |> String.split(".")
          |> Enum.map(&Macro.camelize/1)
          |> Enum.join(".")

        {mod_name, []}
    end
  end

  defp topological_sort_instances(instances) do
    names = Map.keys(instances)
    # Build dependency graph
    deps =
      Map.new(instances, fn {name, inst} ->
        expr_text =
          Enum.join(
            [
              inst.value || "",
              inst.if_expr || "",
              inst.pos || "",
              inst.size || "",
              inst.io || ""
            ],
            " "
          )

        referenced =
          Enum.filter(names, fn other ->
            other != name and String.contains?(expr_text, other)
          end)

        # Positional instances with user types depend on all value instances
        # (since user types may reference other instances via parent params)
        extra_deps =
          if inst.pos != nil and inst.type != nil and inst.value == nil do
            Enum.filter(names, fn other ->
              other != name and other not in referenced and
                instances[other].value != nil
            end)
          else
            []
          end

        {name, referenced ++ extra_deps}
      end)

    # Kahn's algorithm
    sorted = topological_sort_kahn(names, deps)
    Enum.map(sorted, fn name -> {name, instances[name]} end)
  end

  defp topological_sort_kahn(names, deps) do
    # in_degree: count how many deps each node has
    in_degree = Map.new(names, fn n -> {n, length(Map.get(deps, n, []))} end)
    queue = Enum.filter(names, fn n -> Map.get(in_degree, n, 0) == 0 end) |> :queue.from_list()
    do_topological_sort(queue, deps, in_degree, names, [])
  end

  defp do_topological_sort(queue, deps, in_degree, all_names, result) do
    case :queue.out(queue) do
      {:empty, _} ->
        # Add any remaining nodes (cycle handling)
        remaining = all_names -- result
        result ++ remaining

      {{:value, node}, queue} ->
        result = result ++ [node]
        # Find nodes that depend on this one
        dependents =
          Enum.filter(all_names, fn n ->
            n not in result and node in Map.get(deps, n, [])
          end)

        {queue, in_degree} =
          Enum.reduce(dependents, {queue, in_degree}, fn dep, {q, id} ->
            new_degree = Map.get(id, dep, 0) - 1
            id = Map.put(id, dep, new_degree)

            if new_degree == 0 do
              {:queue.in(dep, q), id}
            else
              {q, id}
            end
          end)

        do_topological_sort(queue, deps, in_degree, all_names, result)
    end
  end

